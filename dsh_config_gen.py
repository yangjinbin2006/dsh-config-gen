from typing import Dict, List, Optional, Tuple

VERSION = "1.0.0"

OK = "OK"
WARN = "WARN"
FAIL = "FAIL"
INFO = "INFO"


# --------------------------------------------------------------------------
# Model definition
# --------------------------------------------------------------------------


@dataclass
class ModelDef:
    id: str
    context_window: int = 128000
    max_tokens: int = 8192
    vision: bool = False
    reasoning_efforts: Dict[str, str] = field(default_factory=dict)

    def render(self, indent: str) -> str:
        lines = ["%s- id: %s" % (indent, yaml_scalar(self.id))]
        lines.append("%s  contextWindow: %d" % (indent, self.context_window))
        lines.append("%s  maxTokens: %d" % (indent, self.max_tokens))
        if self.reasoning_efforts:
            lines.append("%s  reasoningEfforts:" % indent)
            for key, value in self.reasoning_efforts.items():
                lines.append("%s    %s: %s" % (indent, key, yaml_scalar(value)))
        if self.vision:
            lines.append("%s  supportsVision: true" % indent)
        return "\n".join(lines)


@dataclass
class PatchConfig:
    provider: str = "local-bridge"
    display_name: str = "Local Bridge"
    base_url: str = "http://127.0.0.1:8080/v1"
    api_key_env: str = "BRIDGE_API_KEY"
    api: str = "openai-completions"
    thinking_format: str = "openai"
    supports_reasoning_effort: bool = True
    supports_developer_role: bool = False
    default_model: str = ""
    default_reasoning_effort: str = "high"
    models: List[ModelDef] = field(default_factory=list)
    disable_session_log: bool = True

    def resolved_default(self) -> str:
        if self.default_model:
            return self.default_model
        return self.models[0].id if self.models else ""


# --------------------------------------------------------------------------
# YAML emission
# --------------------------------------------------------------------------

# YAML plain scalars only need quoting in a few specific situations. Getting
# this wrong is ugly rather than broken, but a config file that looks unfamiliar
# is a config file people edit by hand and break.
_PLAIN_LEADING_UNSAFE = "-?:,[]{}#&*!|>'\"%@` "
_RESERVED_WORDS = {"true", "false", "null", "yes", "no", "on", "off", "~"}


def yaml_scalar(value: str) -> str:
    text = str(value)
    if text == "":
        return '""'
    needs_quotes = (
        text.lower() in _RESERVED_WORDS
        or text[0] in _PLAIN_LEADING_UNSAFE
        or text[-1] == " "
        or ": " in text
        or text.endswith(":")
        or " #" in text
        or "\n" in text
        or "\t" in text
    )
    if needs_quotes:
        escaped = text.replace("\\", "\\\\").replace('"', '\\"')
        return '"%s"' % escaped
    return text


def render(config: PatchConfig) -> str:
    """Emit a complete patch layer as text."""
    blocks: List[str] = []
    header = [
        "# dsh patch layer, generated by dsh-config-gen %s" % VERSION,
        "#",
        "# Location: ~/.dsh/profiles/<profile>/cordis.patch.yml",
        "# Applied after every bundle layer. A top-level YAML array of loader",
        "# patch entries: id-targeted config overrides, disables, insert lists.",
        "#",
        "# The API key is NOT stored here. Put it in the environment variable",
        "# named by apiKeyEnv, then fully restart dsh so it inherits the value.",
        "",
    ]
    blocks.append("\n".join(header))

    default = config.resolved_default()
    if default:
        blocks.append(
            "\n".join(
                [
                    "- id: agent-default-model",
                    '  name: "@deepseek-ai/dsh-agent-default-model"',
                    "  config:",
                    "    provider: %s" % yaml_scalar(config.provider),
                    "    model: %s" % yaml_scalar(default),
                    "    reasoningEffort: %s" % yaml_scalar(config.default_reasoning_effort),
                ]
            )
        )

    provider_lines = [
        "- id: llm-pi-ai",
        '  name: "@deepseek-ai/dsh-llm-pi-ai"',
        "  config:",
        "    providers:",
        "      %s:" % yaml_scalar(config.provider),
        "        displayName: %s" % yaml_scalar(config.display_name),
        "        apiKeyEnv: %s" % yaml_scalar(config.api_key_env),
        "        api: %s" % yaml_scalar(config.api),
        "        baseURL: %s" % yaml_scalar(config.base_url),
        "        compat:",
        "          thinkingFormat: %s" % yaml_scalar(config.thinking_format),
        "          supportsReasoningEffort: %s" % str(config.supports_reasoning_effort).lower(),
        "          supportsDeveloperRole: %s" % str(config.supports_developer_role).lower(),
    ]
    if config.models:
        provider_lines.append("        models:")
        for model in config.models:
            provider_lines.append(model.render("          "))
    blocks.append("\n".join(provider_lines))

    if config.disable_session_log:
        blocks.append(
            "\n".join(
                [
                    "# Optional: stop shipping transcripts to the hosted session log.",
                    "- id: session-log-deepseek",
                    '  name: "@deepseek-ai/dsh-session-log-deepseek"',
                    "  config:",
                    "    enabled: false",
                ]
            )
        )

    return "\n\n".join(blocks) + "\n"


