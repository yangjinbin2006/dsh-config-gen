#!/usr/bin/env python3
"""dsh-config-gen — generate and validate a DeepSeek Harness patch layer.

Zero third-party dependencies. Python 3.8+.

The dsh patch layer (``~/.dsh/profiles/<profile>/cordis.patch.yml``) is a YAML
list of loader patches applied after the bundled layers. It is powerful and
completely unforgiving: one wrong indent under ``providers:`` and your provider
silently does not exist, while one careless paste puts a live API key into a
file people routinely screenshot.

This tool does two things about that:

  generate   Build a correct patch layer from flags, a preset, or a short wizard.
             It never writes a literal API key -- only the name of an
             environment variable.
  validate   Read an existing patch layer and report structural problems,
             plaintext secrets, and ids that will not resolve.

Usage:

    python dsh_config_gen.py --preset minimal --print
    python dsh_config_gen.py --wizard
    python dsh_config_gen.py --base-url http://127.0.0.1:8080/v1 \
        --api-key-env MY_KEY --models chat-model --print
    python dsh_config_gen.py --validate ~/.dsh/profiles/desktop/cordis.patch.yml

License: MIT
"""

from __future__ import annotations

import argparse
import json
