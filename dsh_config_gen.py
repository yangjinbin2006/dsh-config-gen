def wizard() -> PatchConfig:
    print("dsh-config-gen %s -- interactive setup" % VERSION)
    print("Press Enter to accept the value in brackets.\n")

    config = PatchConfig()

    config.base_url = _prompt("Bridge base URL", config.base_url)
    config.api_key_env = _prompt("Environment variable holding the API key", config.api_key_env)
    config.provider = _prompt("Provider id (lowercase, no spaces)", config.provider)
    config.display_name = _prompt("Display name", config.display_name)

    models: List[ModelDef] = []
    print("\nModel ids, one per line. Blank line to finish.")
    print("Tip: copy the exact ids from the endpoint's /v1/models -- they are case sensitive.")
    while True:
        raw = input("  model id: ").strip()
        if not raw:
            break
        context = _prompt_int("    contextWindow", 128000)
        max_tokens = _prompt_int("    maxTokens", 8192)
        vision = _prompt_bool("    supportsVision", True)
        models.append(ModelDef(raw, context, max_tokens, vision))

    if not models:
        fallback = _prompt("\nNo models entered. Default model id", "")
        if fallback:
            models.append(ModelDef(fallback))

    config.models = models
    if models:
        config.default_model = _prompt("Default model", models[0].id)
    config.default_reasoning_effort = _prompt("Default reasoning effort", "high")
    config.disable_session_log = _prompt_bool("Disable hosted session log", True)
    return config


def _prompt(label: str, default: str) -> str:
    suffix = " [%s]" % default if default else ""
    value = input("%s%s: " % (label, suffix)).strip()
    return value or default


def _prompt_int(label: str, default: int) -> int:
    raw = _prompt(label, str(default))
    try:
        return int(raw)
    except ValueError:
        print("    not a number, using %d" % default)
        return default


def _prompt_bool(label: str, default: bool) -> bool:
    default_text = "Y/n" if default else "y/N"
    raw = input("%s [%s]: " % (label, default_text)).strip().lower()
    if not raw:
        return default
    return raw in ("y", "yes", "true", "1")


