@dataclass
class Issue:
    level: str
    area: str
    message: str
    line: int = 0
    hint: str = ""


def _iter_lines(text: str):
    for idx, raw in enumerate(text.splitlines(), 1):
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        yield idx, len(raw) - len(raw.lstrip()), stripped


def validate_text(text: str) -> List[Issue]:
    issues: List[Issue] = []
    lines = list(_iter_lines(text))

    if not text.strip():
        return [Issue(FAIL, "file", "patch layer is empty")]

    # The patch layer must be a top-level array of entries.
    first = lines[0][2] if lines else ""
    if not first.startswith("- ") and not first.startswith("-"):
        issues.append(
            Issue(
                FAIL,
                "structure",
                "patch layer must be a top-level YAML array",
                line=lines[0][0] if lines else 0,
                hint="Every entry starts with '- id: ...'. A bare mapping here is ignored by the loader.",
            )
        )

    # Collect entries.
    entry_indent: Optional[int] = None
    entries: List[Tuple[int, str, int]] = []  # (line_no, id, index)
    for idx, (line_no, ind, body) in enumerate(lines):
        if body.startswith("- ") or body == "-":
            if entry_indent is None:
                entry_indent = ind
            if ind == entry_indent:
                ident = ""
                if body.startswith("- id:"):
                    ident = body.split(":", 1)[1].strip()
                elif body.startswith("- name:"):
                    ident = "(no id) " + body.split(":", 1)[1].strip()
                entries.append((line_no, ident, idx))

    if not entries:
        issues.append(Issue(FAIL, "structure", "no loader entries found"))
        return issues

    # Duplicate ids.
    seen: Dict[str, int] = {}
    for line_no, ident, _ in entries:
        if not ident:
            continue
        if ident in seen:
            issues.append(
                Issue(
                    WARN,
                    "structure",
                    "duplicate entry id %r" % ident,
                    line=line_no,
                    hint="Later entries win; the earlier one is silently overridden (first seen line %d)." % seen[ident],
                )
            )
        else:
            seen[ident] = line_no

    # Entries without an id cannot be addressed by later layers.
    for line_no, ident, _ in entries:
        if not ident:
            issues.append(
                Issue(WARN, "structure", "entry without an id", line=line_no,
                      hint="An id-targeted patch layer is pointless on entries that cannot be targeted.")
            )

    # Plaintext keys.
    for line_no, _, body in lines:
        if body.startswith("apiKey:") and not body.split(":", 1)[1].strip().startswith("!!"):
            value = body.split(":", 1)[1].strip()
            if value:
                issues.append(
                    Issue(
                        FAIL,
                        "secret",
                        "plaintext apiKey value",
                        line=line_no,
                        hint="Use apiKeyEnv instead, then rotate this key if the file was ever shared.",
                    )
                )

    # providers mapping.
    providers = _find_providers(text)
    if not providers:
        has_llm = any("llm-pi-ai" in body for _, _, body in lines)
        if has_llm:
            issues.append(
                Issue(FAIL, "provider", "llm-pi-ai entry has no 'providers:' mapping",
                      hint="Indentation under config: must be exactly two spaces deeper than the entry key.")
            )
        else:
            issues.append(Issue(WARN, "provider", "no llm-pi-ai entry",
                                hint="Without it, dsh has no custom provider at all."))

    for name, info in providers.items():
        base_url = info.get("baseURL", "")
        api_key_env = info.get("apiKeyEnv", "")

        if not base_url:
            issues.append(Issue(FAIL, "provider", "provider %r has no baseURL" % name))
        else:
            if not re.match(r"^https?://", base_url):
                issues.append(Issue(FAIL, "provider", "provider %r baseURL is not http(s): %s" % (name, base_url)))
            if not base_url.rstrip("/").endswith("/v1"):
                issues.append(
                    Issue(
                        WARN,
                        "provider",
                        "provider %r baseURL does not end with /v1: %s" % (name, base_url),
                        hint="The OpenAI-compatible routes live under /v1. Without it you get 404s on every call.",
                    )
                )
            if "localhost" in base_url:
                issues.append(
                    Issue(
                        INFO,
                        "provider",
                        "provider %r uses 'localhost'" % name,
                        hint="On some Windows setups localhost resolves to ::1 while the bridge binds 127.0.0.1. "
                             "Use the literal address if connections are refused.",
                    )
                )

        if not api_key_env:
            issues.append(
                Issue(
                    WARN,
                    "provider",
                    "provider %r has no apiKeyEnv" % name,
                    hint="Without it the client has no documented place to read the credential from.",
                )
            )
        elif not os.environ.get(api_key_env):
            issues.append(
                Issue(
                    WARN,
                    "provider",
                    "env var %r is not set in this shell" % api_key_env,
                    hint="Expected if you are validating from a different shell than the one that launches dsh.",
                )
            )

        models = info.get("models", [])
        if not models:
            issues.append(
                Issue(WARN, "provider", "provider %r declares no models" % name,
                      hint="A provider with no models cannot be selected.")
            )

    # Default model must resolve.
    default_model = _find_default_model(text)
    if default_model and providers:
        declared = set()
        for info in providers.values():
            declared.update(info.get("models", []))
        if declared and default_model not in declared:
            issues.append(
                Issue(
                    FAIL,
                    "model",
                    "agent-default-model points at %r, which no provider declares" % default_model,
                    hint="The first request will fail with a model-not-found style error.",
                )
            )

    if not issues:
        issues.append(Issue(OK, "config", "patch layer looks structurally sound"))

    return issues


def _find_providers(text: str) -> Dict[str, Dict[str, object]]:
    lines = list(_iter_lines(text))
    result: Dict[str, Dict[str, object]] = {}

    for i, (_, indent, content) in enumerate(lines):
        if content.rstrip() != "providers:":
            continue

        blocks: List[Tuple[str, int]] = []
        child_indent: Optional[int] = None
        j = i + 1
        while j < len(lines) and lines[j][1] > indent:
            _, ind, body = lines[j]
            if child_indent is None:
                child_indent = ind
            if ind == child_indent and body.endswith(":") and not body.startswith("- "):
                blocks.append((body[:-1].strip(), j))
            j += 1

        for bi, (name, start) in enumerate(blocks):
            end = blocks[bi + 1][1] if bi + 1 < len(blocks) else j
            info: Dict[str, object] = {"models": []}
            for k in range(start + 1, end):
                body = lines[k][2]
                if body.startswith("baseURL:"):
                    info["baseURL"] = body.split(":", 1)[1].strip().strip("'\"")
                elif body.startswith("apiKeyEnv:"):
                    info["apiKeyEnv"] = body.split(":", 1)[1].strip().strip("'\"")
                elif body.startswith("- id:"):
                    model_id = body.split(":", 1)[1].strip().strip("'\"")
                    if model_id:
                        info["models"].append(model_id)  # type: ignore[union-attr]
            result[name] = info

    return result


def _find_default_model(text: str) -> str:
    lines = list(_iter_content_or_all(text))
    for i, (_, _, content) in enumerate(lines):
        if content.startswith("model:") and i > 0:
            window = " ".join(c for _, _, c in lines[max(0, i - 8): i + 1])
            if "agent-default-model" in window:
                return content.split(":", 1)[1].strip().strip("'\"")
    return ""


def _iter_content_or_all(text: str):
    for idx, raw in enumerate(text.splitlines(), 1):
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        yield idx, len(raw) - len(raw.lstrip()), stripped


MARKS = {OK: "[ OK ]", WARN: "[WARN]", FAIL: "[FAIL]", INFO: "[INFO]"}


def render_issues(issues: List[Issue], path: Optional[Path] = None) -> str:
    out: List[str] = ["dsh-config-gen %s" % VERSION]
    if path:
        out.append("validating %s" % path)
    out.append("=" * 62)
    for issue in issues:
        location = (" line %d" % issue.line) if issue.line else ""
        out.append("%s %-10s %s%s" % (MARKS.get(issue.level, "[????]"), issue.area, issue.message, location))
        if issue.hint:
            for wrapped in _wrap(issue.hint, 56):
                out.append("       " + wrapped)
    out.append("-" * 62)
    failures = sum(1 for i in issues if i.level == FAIL)
    warnings = sum(1 for i in issues if i.level == WARN)
    out.append("%d failure(s), %d warning(s)" % (failures, warnings))
    return "\n".join(out)


def _wrap(text: str, width: int) -> List[str]:
    words = text.split()
    lines: List[str] = []
    current = ""
    for word in words:
        if not current:
            current = word
        elif len(current) + 1 + len(word) <= width:
            current += " " + word
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines or [""]


