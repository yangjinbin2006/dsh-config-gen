def default_output_path(profile: str) -> Path:
    home = Path(os.environ.get("DSH_HOME") or (Path.home() / ".dsh"))
    return home / "profiles" / profile / "cordis.patch.yml"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="dsh-config-gen",
        description="Generate or validate a DeepSeek Harness patch layer.",
    )
    parser.add_argument("--preset", choices=sorted(PRESETS), help="start from a built-in preset")
    parser.add_argument("--wizard", action="store_true", help="interactive setup")
    parser.add_argument("--provider", help="provider id, e.g. local-bridge")
    parser.add_argument("--display-name", help="human readable provider name")
    parser.add_argument("--base-url", help="OpenAI-compatible base URL, must end in /v1")
    parser.add_argument("--api-key-env", help="name of the env var holding the key")
    parser.add_argument("--model", action="append", default=[], metavar="ID",
                        help="model id (repeatable); optional ID:CTX:MAX syntax")
    parser.add_argument("--default-model", help="model used by agent-default-model")
    parser.add_argument("--reasoning-effort", default="high", help="default reasoning effort")
    parser.add_argument("--allow-developer-role", action="store_true",
                        help="emit supportsDeveloperRole: true (rarely correct)")
    parser.add_argument("--keep-session-log", action="store_true",
                        help="do not disable the hosted session log")
    parser.add_argument("--print", dest="to_stdout", action="store_true", help="write to stdout instead of a file")
    parser.add_argument("--output", help="output path (default: ~/.dsh/profiles/<profile>/cordis.patch.yml)")
    parser.add_argument("--profile", default="desktop", help="profile name used for the default output path")
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    parser.add_argument("--validate", metavar="PATH", help="validate an existing patch layer and exit")
    parser.add_argument("--json", action="store_true", help="machine readable validation output")
    parser.add_argument("--version", action="version", version="dsh-config-gen %s" % VERSION)
    return parser


def parse_model_arg(raw: str) -> ModelDef:
    parts = raw.split(":")
    model_id = parts[0]
    context = 128000
    max_tokens = 8192
    if len(parts) >= 2 and parts[1].isdigit():
        context = int(parts[1])
    if len(parts) >= 3 and parts[2].isdigit():
        max_tokens = int(parts[2])
    return ModelDef(model_id, context, max_tokens, vision=True)


def main(argv: Optional[List[str]] = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass

    args = build_parser().parse_args(argv)

    # ---- validate mode ---------------------------------------------------
    if args.validate:
        path = Path(args.validate).expanduser()
        if not path.is_file():
            print("No such file: %s" % path, file=sys.stderr)
            return 2
        issues = validate_text(path.read_text(encoding="utf-8", errors="replace"))
        if args.json:
            print(json.dumps(
                {"path": str(path), "issues": [i.__dict__ for i in issues]},
                indent=2,
                ensure_ascii=False,
            ))
        else:
            print(render_issues(issues, path))
        return 1 if any(i.level == FAIL for i in issues) else 0

    # ---- generate mode ---------------------------------------------------
    if args.wizard:
        config = wizard()
    else:
        config = PatchConfig()
        if args.preset:
            base = PRESETS[args.preset]
            config = PatchConfig(**{k: (list(v) if isinstance(v, list) else v)
                                    for k, v in base.__dict__.items()})
        if args.provider:
            config.provider = args.provider
        if args.display_name:
            config.display_name = args.display_name
        if args.base_url:
            config.base_url = args.base_url
        if args.api_key_env:
            config.api_key_env = args.api_key_env
        if args.reasoning_effort:
            config.default_reasoning_effort = args.reasoning_effort
        if args.allow_developer_role:
            config.supports_developer_role = True
        if args.keep_session_log:
            config.disable_session_log = False
        if args.model:
            config.models = [parse_model_arg(m) for m in args.model]
        if args.default_model:
            config.default_model = args.default_model

    if not config.models:
        print("No models configured. Pass --model ID (repeatable) or use --wizard.", file=sys.stderr)
        return 1

    rendered = render(config)

    # Validate what we are about to emit -- never ship a broken layer.
    issues = validate_text(rendered)
    blocking = [i for i in issues if i.level == FAIL]
    if blocking:
        print(render_issues(blocking), file=sys.stderr)
        print("\nRefusing to write a config that fails validation.", file=sys.stderr)
        return 1

    if args.to_stdout:
        print(rendered, end="")
        return 0

    target = Path(args.output).expanduser() if args.output else default_output_path(args.profile)
    if target.exists() and not args.force:
        print("Refusing to overwrite %s\nUse --force, or --print to review the output first." % target, file=sys.stderr)
        return 2

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered, encoding="utf-8")
    print("wrote %s" % target)
    print("next: make sure %s is set, then fully restart dsh" % config.api_key_env)
    return 0


if __name__ == "__main__":
    sys.exit(main())
